def _tts_to_wav(text: str, path: Path):
    try:
        import pyttsx3  # type: ignore
        engine = pyttsx3.init()
        engine.setProperty("rate", 145)
        voices = engine.getProperty("voices")
        if voices:
            engine.setProperty("voice", voices[random.randint(0, min(1, len(voices) - 1))].id)
        engine.save_to_file(text, str(path))
        engine.runAndWait()
    except Exception:
        _silent_wav(path, seconds=3)


def _silent_wav(path: Path, seconds: int = 3):
    """Minimal valid WAV with near-silence (valid for SpeechRecognition input)."""
    sr, n = 16000, 16000 * seconds
    with wave.open(str(path), "w") as wf:
        wf.setnchannels(1)
        wf.setsampwidth(2)
        wf.setframerate(sr)
        wf.writeframes(struct.pack(f"<{n}h", *([0] * n)))


